// Keep the database denylist synchronized with the browser policy.
import { readFile, writeFile } from 'node:fs/promises';
import { blockedFragments, blockedWords, collapseLetters } from '../leaderboard-policy.js';
const literal = values => `array[${values.map(value => `'${collapseLetters(value).replaceAll("'", "''")}'`).join(',')}]::text[]`;
const template = await readFile('supabase/leaderboard.template.sql', 'utf8');
const sql = '-- Generated by node scripts/generate-leaderboard-sql.mjs. Run this entire file in the Supabase SQL editor.\n' + template.replace('__FRAGMENTS__', literal(blockedFragments)).replace('__WORDS__', literal(blockedWords));
await writeFile('supabase/leaderboard.sql', sql);
